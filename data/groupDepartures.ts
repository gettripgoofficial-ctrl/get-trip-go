export const getGroupDepartureBySlug = (slug: string) =>
  groupDepartures.find(p => p.slug === slug)

export const getAllCountries = () => {
  const all = groupDepartures.flatMap(p => p.countries)
  return [...new Set(all)].sort()
}

export const getAllSeries = () =>
  [...new Set(groupDepartures.map(p => p.series))]

export const getAllMonths = () => {
  const months = groupDepartures.flatMap(p =>
    p.departureDates.map(d => d.split(" ")[1] + " " + d.split(" ")[2])
  )
  return [...new Set(months)]
}